create table if not exists public.pontuacoes (
  id bigint generated by default as identity primary key,
  nome text not null,
  jogo text not null,
  melhor_pontuacao integer not null default 0,
  ultima_pontuacao integer not null default 0
);

alter table public.pontuacoes enable row level security;

drop policy if exists "Permitir leitura das pontuacoes" on public.pontuacoes;
create policy "Permitir leitura das pontuacoes"
  on public.pontuacoes for select
  to anon
  using (true);

drop policy if exists "Permitir insercao das pontuacoes" on public.pontuacoes;
create policy "Permitir insercao das pontuacoes"
  on public.pontuacoes for insert
  to anon
  with check (true);
